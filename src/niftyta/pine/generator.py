"""Phase 6: Pine Script v6 strategy() generator for the three rule sets.
Each script uses the same parameters as config/*.yaml and the same signal definitions as
src/niftyta/backtest/strategies.py. Differences in execution (costs, sizing, slippage units)
are written into the notes file, because TradingView cannot reproduce them exactly."""
from __future__ import annotations

from pathlib import Path

from ..backtest.costs import buy_cost_rate, load_costs, sell_cost_rate

STRATEGY_KEYS = {"rsi": "RSI(14) 30/70", "ema_cross": "EMA 9/21 cross", "bbands": "Bollinger 20,2"}


def _commission_pct(costs: dict) -> float:
    """Pine applies one commission rate to both sides; use the average of buy and sell (in %)."""
    return (buy_cost_rate(costs) + sell_cost_rate(costs)) / 2 * 100


def _slippage_ticks(costs: dict, price: float, tick: float) -> int:
    return max(0, round(price * costs["slippage_per_side"] / tick))


HEADER = """//@version=6
// Generated by NiftyTA. {title}
// Rules: {rules}
// Signals on the close of each bar; orders fill at the next bar's open (Pine default).
// NOT tested in TradingView by NiftyTA. Verify by pasting into the Pine Editor.
strategy("{title}", overlay={overlay}, initial_capital=100000, currency=currency.INR,
     default_qty_type=strategy.percent_of_equity, default_qty_value=100,
     commission_type=strategy.commission.percent, commission_value={commission},
     slippage={slippage}, process_orders_on_close=false)
"""

FOOTER = """
if longEntry and strategy.position_size == 0
    strategy.entry("Long", strategy.long)
if longExit and strategy.position_size > 0
    strategy.close("Long", comment="Exit")

plotshape(longEntry, title="Buy signal", location=location.belowbar, style=shape.triangleup, color=color.green, size=size.small)
plotshape(longExit, title="Sell signal", location=location.abovebar, style=shape.triangledown, color=color.red, size=size.small)
"""


def _rsi(p, costs, price, tick):
    body = f"""
rsiLen = input.int({p['rsi']['period']}, "RSI length")
entryLevel = input.float({p['rsi_entry']}, "Entry: RSI crosses above")
exitLevel = input.float({p['rsi_exit']}, "Exit: RSI crosses below")
rsi = ta.rsi(close, rsiLen)
longEntry = ta.crossover(rsi, entryLevel)
longExit = ta.crossunder(rsi, exitLevel)
plot(rsi, "RSI", color=color.purple)
hline(entryLevel, "Entry level", color=color.green, linestyle=hline.style_dotted)
hline(exitLevel, "Exit level", color=color.red, linestyle=hline.style_dotted)
"""
    return body, False


def _ema(p, costs, price, tick):
    body = f"""
fastLen = input.int({p['ema_fast']['period']}, "Fast EMA")
slowLen = input.int({p['ema_slow']['period']}, "Slow EMA")
emaFast = ta.ema(close, fastLen)
emaSlow = ta.ema(close, slowLen)
longEntry = ta.crossover(emaFast, emaSlow)
longExit = ta.crossunder(emaFast, emaSlow)
plot(emaFast, "EMA fast", color=color.blue)
plot(emaSlow, "EMA slow", color=color.orange)
"""
    return body, True


def _bb(p, costs, price, tick):
    b = p["bbands"]
    body = f"""
bbLen = input.int({b['period']}, "Bollinger length")
bbMult = input.float({b['std']}, "Bollinger std dev")
[bbMid, bbUp, bbLow] = ta.bb(close, bbLen, bbMult)
longEntry = ta.crossover(close, bbLow)
longExit = ta.crossunder(close, bbUp)
plot(bbUp, "Upper band", color=color.gray)
plot(bbMid, "Middle band", color=color.gray, style=plot.style_stepline)
plot(bbLow, "Lower band", color=color.gray)
"""
    return body, True


BUILDERS = {"rsi": _rsi, "ema_cross": _ema, "bbands": _bb}
RULES_TEXT = {
    "rsi": "Buy when RSI crosses above entry level; sell when RSI crosses below exit level.",
    "ema_cross": "Buy when fast EMA crosses above slow EMA; sell when it crosses below.",
    "bbands": "Buy when close crosses back above the lower band; sell when it crosses back below the upper band.",
}


def generate(strategy_key: str, symbol: str, timeframe: str, params: dict, costs: dict | None = None,
             last_price: float = 1000.0, tick: float = 0.05) -> tuple[str, str]:
    """Return (pine_source, notes_markdown)."""
    if strategy_key not in BUILDERS:
        raise ValueError(f"unknown strategy {strategy_key}; choose from {list(BUILDERS)}")
    c = costs or load_costs()
    p = dict(params)
    strat = _load_strategy_config()
    p["rsi_entry"] = strat["rsi"]["entry_cross_above"]
    p["rsi_exit"] = strat["rsi"]["exit_cross_below"]
    commission = _commission_pct(c)
    slip = _slippage_ticks(c, last_price, tick)
    body, overlay = BUILDERS[strategy_key](p, c, last_price, tick)
    title = f"{symbol} {STRATEGY_KEYS[strategy_key]} ({timeframe}) - NiftyTA"
    head = HEADER.format(title=title, rules=RULES_TEXT[strategy_key], overlay="true" if overlay else "false",
                         commission=f"{commission:.4f}", slippage=slip)
    source = head + body + FOOTER
    notes = _notes(symbol, timeframe, strategy_key, commission, slip, c, tick, last_price)
    return source, notes


def _load_strategy_config() -> dict:
    import yaml
    from pathlib import Path as _P
    root = _P(__file__).resolve().parents[3]
    return yaml.safe_load(open(root / "config" / "strategies.yaml"))


def _notes(symbol, tf, key, commission, slip, c, tick, price) -> str:
    return f"""# Pine Script notes: {symbol} {STRATEGY_KEYS[key]} ({tf})

## How to test in TradingView Free
1. Open the chart for {symbol} on NSE with the **{tf}** timeframe (daily, weekly or monthly).
2. Open the Pine Editor, paste the script, click **Save**, then **Add to chart**.
3. Open the **Strategy Tester** tab. Compare the number of trades and the entry and exit dates
   with `reports/{symbol}_{tf}_backtest_trades.csv`. Dates should match within one bar.
4. Check the signal markers on the chart against the trade list.

## Known differences between Python and TradingView
- **Commission:** TradingView applies one rate to both sides. The script uses the average of the
  buy and sell rates: {commission:.4f}%. Python applies buy and sell rates separately (STT on sells only).
- **Slippage:** Python uses {c['slippage_per_side']:.2%} of price per side. TradingView takes slippage in
  ticks: {slip} ticks at about {price:.0f} INR with tick size {tick}. This is approximate and changes with price.
- **Position sizing:** Python buys whole shares with 100% of cash after costs. TradingView uses
  100% of equity, so it can differ slightly in share count and return.
- **Data:** TradingView uses its own price feed. Adjusted or raw prices may differ from NiftyTA's NSE data.
- **Rounding:** Python signals use the same definitions, but at exact equality (for example RSI exactly 30)
  the Python rule is strict and TradingView's crossover rule may differ by one bar.
- **Open position at the end:** the Python backtest marks an open position to market at the end; the
  Strategy Tester reports it as an open trade.

## Not verified
NiftyTA has not run this script in TradingView. Check the results yourself before relying on it.
"""


def write(strategy_key: str, symbol: str, timeframe: str, params: dict, out_dir: Path,
          last_price: float = 1000.0) -> tuple[Path, Path]:
    source, notes = generate(strategy_key, symbol, timeframe, params, last_price=last_price)
    out_dir.mkdir(parents=True, exist_ok=True)
    tag = f"{symbol}_{timeframe}_{strategy_key}"
    pine_path = out_dir / f"{tag}.pine"
    notes_path = out_dir / f"{tag}_NOTES.md"
    pine_path.write_text(source)
    notes_path.write_text(notes)
    return pine_path, notes_path


# ---------- GFS (Grandfather-Father-Son + RSI divergence) ----------
GFS_TEMPLATE = Path(__file__).with_name("gfs_template.pine")


def generate_gfs(symbol: str, params: dict | None = None, costs: dict | None = None) -> str:
    """Pine v6 source for the GFS strategy. Defaults come from the `gfs` block of config/strategies.yaml.
    Run it on the Son timeframe chart. Spec: docs/strategies/gfs_spec.md."""
    g = params or _load_strategy_config()["gfs"]
    c = costs or load_costs()
    vals = {
        "grandfather_tf": {"1D": "D", "1W": "W", "1M": "M"}[g["grandfather_tf"]],
        "father_tf": {"1D": "D", "1W": "W", "1M": "M"}[g["father_tf"]],
        "rsi_period": g["rsi_period"], "htf_rsi_min": g["htf_rsi_min"],
        "pullback_low": g["pullback_low"], "pullback_high": g["pullback_high"],
        "pullback_lookback": g["pullback_lookback"], "alert_valid_bars": g["alert_valid_bars"],
        "divergence_swing_bars": g["divergence_swing_bars"], "divergence_min_gap": g["divergence_min_gap"],
        "divergence_max_gap": g["divergence_max_gap"], "divergence_recent": g["divergence_recent"],
        "exit_rr": g["exit_rr"], "scale_rsi": g["scale_rsi"], "scale_pct": g["scale_fraction"] * 100,
        "rest_exit_rsi": g["rest_exit_rsi"], "commission": f"{_commission_pct(c):.4f}",
        "title": f"{symbol} GFS + RSI Divergence ({g['son_tf']}) - NiftyTA",
    }
    src = GFS_TEMPLATE.read_text()
    for k, v in vals.items():
        src = src.replace(f"@{k}@", str(v))
    return src


def write_gfs(symbol: str, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{symbol}_gfs.pine"
    path.write_text(generate_gfs(symbol))
    return path
